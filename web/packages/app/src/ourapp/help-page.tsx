export const HelpPage: Component = () => {
  const [open, setOpen] = createSignal<number | null>(0)
  const toggle = (i: number) => setOpen(open() === i ? null : i)

  return (
    <div class="ourapp-settings">
      <DotWaveBackground />
      <AppTopbar active="help" />

      <main class="ourapp-settings__main">
        <h1 class="ourapp-settings__title">
          <em>Помощь</em>
        </h1>
        <p class="ourapp-settings__lede">
          Частые вопросы о работе с Isaac. Не нашли ответ — напишите нам на{" "}
          <a href="mailto:support@isaac-ai.ru" class="ourapp-settings__link">
            support@isaac-ai.ru
          </a>
          .
        </p>

        <section class="ourapp-faq">
          <For each={FAQ}>
            {(item, i) => (
              <div class="ourapp-faq__item" classList={{ "ourapp-faq__item--open": open() === i() }}>
                <button
                  type="button"
                  class="ourapp-faq__q"
                  aria-expanded={open() === i()}
                  onClick={() => toggle(i())}
                >
                  <span>{item.q}</span>
                  <span class="ourapp-faq__icon" aria-hidden="true">
                    +
                  </span>
                </button>
                <Show when={open() === i()}>
                  <div class="ourapp-faq__a">{item.a}</div>
                </Show>
              </div>
            )}
          </For>
        </section>
      </main>
    </div>
  )
}
