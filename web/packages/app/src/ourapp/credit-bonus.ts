/**
 * OurApp — «бонусные» кредиты от пасхалки с капсулами на фоне (dot-wave-bg).
 *
 * Пользователь ловит и лопает капсулы, плавающие по волнам, — каждая добавляет
 * +1 кредит к отображаемому балансу. Это чисто клиентский, реактивный счётчик
 * (модульный Solid-сигнал): его читают все места, где показан остаток кредитов
 * (шапка AppTopbar, сайдбар воркспейса), и мгновенно обновляются. На сервере
 * ничего не меняется — это игровой бонус к цифре на экране.
 */
import { createSignal } from "solid-js"

const [creditBonus, setCreditBonus] = createSignal(0)

export { creditBonus }

/** Добавить бонусных кредитов (по умолчанию +1 — за одну лопнутую капсулу). */
export function addCreditBonus(n = 1): void {
  setCreditBonus((c) => c + n)
}
